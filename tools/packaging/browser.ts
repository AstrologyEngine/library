import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, cpSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';
const root = resolve(import.meta.dir, '../..');
const app = join(root, 'examples/configurable-chart');
const out = join(root, 'target/distribution/browser');
const run = (args: string[], cwd = root) => execFileSync(args[0], args.slice(1), { cwd, stdio: 'inherit' });
const about = process.env.CARGO_ABOUT ?? 'cargo-about';
if (execFileSync(about, ['--version'], {encoding:'utf8'}).trim() !== 'cargo-about 0.9.2') throw Error('Install cargo-about 0.9.2');
const sysroot = execFileSync('rustc', ['--print','sysroot'], {cwd:root,encoding:'utf8'}).trim();
const standard = readFileSync(join(sysroot,'share/doc/rust/COPYRIGHT-library.html'));
run(['bun','run','build:wasm'], app);
rmSync(out, {recursive:true,force:true});
run(['bun','x','--no-install','vite','build','--mode','distribution','--outDir',out], app);
const licenses = join(out,'licenses');mkdirSync(licenses,{recursive:true});
run([about,'generate','--locked','--fail','--manifest-path','examples/configurable-chart/wasm/Cargo.toml','--target','wasm32-unknown-unknown','--config','tools/packaging/about.toml','--output-file',join(licenses,'rust.txt'),'tools/packaging/licenses.hbs']);
cpSync(join(root,'LICENSE'),join(licenses,'project.txt'));
cpSync(join(root,'THIRD_PARTY_NOTICES.md'),join(licenses,'adapted-code.md'));
writeFileSync(join(licenses,'rust-standard-library.html'),standard);
const vite = readFileSync(join(app,'node_modules/vite/LICENSE.md'),'utf8').split('# Licenses of bundled dependencies')[0];
writeFileSync(join(licenses,'vite.txt'),vite);
writeFileSync(join(out,'ATTRIBUTION.txt'),'Licenses: licenses/project.txt, adapted-code.md, rust.txt, javascript.md, vite.txt and rust-standard-library.html.\nMPL source is available at the exact-version crate URLs in rust.txt under MPL-2.0.\n');
const index = join(out, 'index.html');
writeFileSync(index, readFileSync(index,'utf8').replace('</body>', '<p><a href="./ATTRIBUTION.txt">Attribution</a></p></body>'));
console.log(`Browser distribution: ${out}`);
